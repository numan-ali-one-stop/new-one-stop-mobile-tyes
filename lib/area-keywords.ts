/**
 * The "Area keywords" sheet (SEO + Google Ads), one row per area keyword, mirroring the spreadsheet columns:
 *   Area | Tier | Keyword | Match type | Pattern | Monthly volume | Decision
 *
 * - "Match type" is a Google Ads setting; "Decision" is the Ads team's call (e.g. "Check volume" =
 *   look up search volume before deciding whether to bid). Neither changes the page by itself.
 * - Core-pattern keywords are the area page's own main phrases, so the page should use them whatever
 *   the volume. `presenceBefore` / `presence` record what we measured on the page before and after.
 */
import type { MatchType, Presence } from './keywords'

export interface AreaKeywordRow {
  /** Area */
  area: string
  /** Area page URL path. */
  targetPath: string
  /** Tier */
  tier: string
  /** Keyword */
  keyword: string
  /** Match type (Google Ads) */
  matchType: MatchType
  /** Pattern (e.g. Core) */
  pattern: string
  /** Monthly volume — empty in the sheet for now. */
  monthlyVolume?: number
  /** Decision (Ads team) */
  decision: string
  /** Presence on the page when we checked it. */
  presenceBefore: Presence
  /** Presence on the page now. */
  presence: Presence
  /** What we found / did. */
  notes: string
}

